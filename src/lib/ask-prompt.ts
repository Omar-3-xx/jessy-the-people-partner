/** What she is told about a question this turn: the law for it, and the web if it was searched. */
export function questionPrompt(input: {
  sources: { name: string; chapter?: string; text: string }[];
  web: { title: string; url: string; text: string }[];
  webWasNeededButOff: boolean;
}): string {
  const law = input.sources.length
    ? input.sources
        .map((s) => `[${s.name}${s.chapter ? ` — ${s.chapter}` : ''}]\n${s.text}`)
        .join('\n\n')
    : '(مفيش نص قريب من السؤال ده)';
  const web = input.web.length
    ? `\n\nمن النت (مصادر ثانوية، مش نص القانون):\n${input.web
        .map((w) => `[${w.title} — ${new URL(w.url).hostname}]\n${w.text}`)
        .join('\n\n')}`
    : input.webWasNeededButOff
      ? '\n\n(السؤال ده محتاج معلومة حالية من النت، والبحث مش متاح دلوقتي. قولي كده بوضوح لو الإجابة مش في النصوص، وما تخمنيش الرقم.)'
      : '';
  return `المصادر:\n${law}${web}`;
}
